/**
 * Emits `multi/src/schemapop_{base,opt}.js` from the REAL generator output.
 *
 * `multi/` was built to probe hand-written codec variants (base + model_1…6)
 * across three engines. Those files are hand-authored, so they answer "which
 * shape is fastest" but not "did schema-pop's generator actually adopt it".
 * This script closes that gap: it drops the current `tsCodec` output — and the
 * frozen copy of what the generator emitted before — into the exact same
 * fixture/correctness/benchmark scaffolding, so both run under the existing
 * `build.sh` + `run_bench.sh` matrix on node (V8), deno (V8) and SpiderMonkey.
 *
 * Engine coverage matters here: the probe's own notes reject `new Array(N)`
 * pre-allocation on V8 (holey-array deopt) while measuring it as a win
 * elsewhere. A JSC-only measurement cannot settle that.
 *
 *   bun src/gen-multi.ts && cd multi && ./build.sh && ./run_bench.sh
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const BENCH_ROOT = join(import.meta.dirname, "..");
const TEMPLATE = join(BENCH_ROOT, "multi/src/base.js");

const CODEC_START = "// CURRENT AUTO-GENERATED CODEC";
const FIXTURE_HEADER = "// FIXTURE — DO NOT MODIFY";

/** Everything from the FIXTURE banner down: fixture, checks, mitata benches. */
function scaffold(): { head: string; tail: string } {
	const template = readFileSync(TEMPLATE, "utf8");
	const codecIdx = template.indexOf(CODEC_START);
	const fixtureIdx = template.indexOf(FIXTURE_HEADER);
	if (codecIdx < 0 || fixtureIdx < 0) {
		throw new Error("multi/src/base.js no longer has the expected section banners");
	}
	// The banner line is preceded by its `// ---` rule; keep the rule with it.
	const ruleBefore = template.lastIndexOf("// ---", fixtureIdx);
	// Head is ONLY the mitata import. The template also declares SIZEOF_* above
	// the codec banner, but the generated codec emits those itself — keeping
	// both would be a duplicate `const` declaration.
	const importLine = template.slice(0, template.indexOf("\n") + 1);
	void codecIdx;
	return { head: importLine, tail: template.slice(ruleBefore) };
}

const transpiler = new Bun.Transpiler({ loader: "ts" });

/**
 * The generated codec is TS. Strip the types, and drop the `export` keywords —
 * vite's lib build only needs the entry's own exports, and the scaffolding
 * references these as plain module-scope bindings.
 */
function codecSource(file: string, suffix: string): string {
	const ts = readFileSync(file.startsWith("src/") ? join(BENCH_ROOT, file) : join(BENCH_ROOT, "generated", file), "utf8");
	const js = transpiler.transformSync(ts);
	return (
		js
			// `export function foo` → `function foo`
			.replace(/^export\s+(function|const|type)\s/gm, "$1 ")
			// The frozen baseline carries `_base`-suffixed names so both codecs can
			// coexist in one process; here each file holds exactly one codec, so
			// normalize back to the plain names the scaffolding calls.
			.replace(/_base\b/g, suffix)
	);
}

const { head, tail } = scaffold();

for (const [name, file] of [
	["schemapop_opt", "data_codec.ts"],
	["schemapop_base", "src/codec-baseline.ts"],
] as const) {
	const body = codecSource(file, "");
	const out = `${head}// -----------------------------------------------------------------------------
// schema-pop generator output — ${name === "schemapop_opt" ? "CURRENT" : "PREVIOUS (frozen)"}
// Generated by src/gen-multi.ts — do not edit by hand.
// -----------------------------------------------------------------------------
${body}
${tail}`;
	const dest = join(BENCH_ROOT, "multi/src", `${name}.js`);
	writeFileSync(dest, out);
	console.log(`→ ${dest}  (${out.length} bytes)`);
}
