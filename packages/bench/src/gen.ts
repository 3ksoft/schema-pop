import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fromModule, SchemaAnalyzer } from "@schema-pop/core";
import { exportPlan } from "@schema-pop/exporter";
import { benchSchema } from "./schema.ts";
import { benchSchemaText } from "./schemaText.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outDir = join(__dirname, "..", "generated");
mkdirSync(outDir, { recursive: true });

function emit(scopeMod: any, name: string) {
	const paths = {
		plan: join(outDir, `${name}_plan.ts`),
		codec: join(outDir, `${name}_codec.ts`)
	};
	const ctx = fromModule(scopeMod.export());
	const { plan } = new SchemaAnalyzer().analyze(ctx, {
		wordSize: "64",
		layout: "aligned",
		mode: "binary",
		version: "1.0.0",
		endian: "le",
	});

	writeFileSync(paths.plan, `export const plan = ${JSON.stringify(plan)};`)

	const generated = exportPlan(plan, "ts:codec");
	const code =
		typeof generated === "string"
			? generated
			: Object.values(generated).join("\n");

	const typeAliases =
		plan.types
			.filter((t) => !(t.kind === "enum" && (t as any).variants?.length === 1))
			.map((t) => `export type ${t.name} = any;`)
			.join("\n") + "\n\n";

	const header =
		"// AUTO-GENERATED by schema-pop ts:codec exporter. Do not edit.\n\n";
	writeFileSync(paths.codec, header + typeAliases + code);

	console.log(`\n→ ${paths.codec}`);
	for (const t of plan.types) {
		const sz = (t as any).paddedSize ?? (t as any).size ?? "?";
		console.log(`  ${t.name.padEnd(14)} ${sz} bytes`);
	}
	console.log(`  code size: ${code.length} bytes`);
}

emit(benchSchema, "data");
emit(benchSchemaText, "text");
