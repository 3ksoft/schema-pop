import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fromModule, SchemaAnalyzer } from "@schema-pop/core";
import { exportPlan } from "@schema-pop/exporter";
import { benchSchema } from "./schema.ts";
import { benchSchemaText } from "./schemaText.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outDir = join(__dirname, "..", "generated");
mkdirSync(outDir, { recursive: true });

function emit(scopeMod: any, outFile: string) {
	const schema = fromModule(scopeMod.export());
	const plan = new SchemaAnalyzer(schema, {
		wordSize: "64",
		autoLayout: false,
		layoutType: "aligned",
		mode: "binary",
	}).analyze("v1", "le");

	const generated = exportPlan(plan, "ts:codec");
	const code =
		typeof generated === "string"
			? generated
			: Object.values(generated).join("\n");

	const typeAliases =
		plan.types
			.filter((t) => !(t.kind === "enum" && (t as any).variants?.length === 1))
			.map((t) => `export type ${t.name} = any;`)
			.join("\n") + "\n\n";

	const header =
		"// AUTO-GENERATED by schema-pop ts:codec exporter. Do not edit.\n\n";
	writeFileSync(join(outDir, outFile), header + typeAliases + code);

	console.log(`\n→ ${outFile}`);
	for (const t of plan.types) {
		const sz = (t as any).paddedSize ?? (t as any).size ?? "?";
		console.log(`  ${t.name.padEnd(14)} ${sz} bytes`);
	}
	console.log(`  code size: ${code.length} bytes`);
}

emit(benchSchema, "codec.ts");
emit(benchSchemaText, "codecText.ts");
